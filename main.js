let currentLang = 'en';

function setText(id, value) {
    const element = document.getElementById(id);
    if (element) {
        element.textContent = value;
    }
}

function setHtml(id, value) {
    const element = document.getElementById(id);
    if (element) {
        element.innerHTML = value;
    }
}

function setStoredLanguage(value) {
    try {
        localStorage.setItem('hypercube_lang', value);
    } catch (error) {
        // Ignore storage errors in restricted browser modes.
    }
}

function getStoredLanguage() {
    try {
        return localStorage.getItem('hypercube_lang');
    } catch (error) {
        return null;
    }
}

function applyLanguage(lang) {
    const dictionary = i18n[lang] || i18n.en;
    currentLang = dictionary.lang;

    document.documentElement.lang = dictionary.lang;
    document.title = dictionary.pageTitle;

    const metaDescription = document.querySelector('meta[name="description"]');
    if (metaDescription) {
        metaDescription.setAttribute('content', dictionary.metaDescription);
    }

    setText('navHomeDesktop', dictionary.nav.home);
    setText('navProjectsDesktop', dictionary.nav.projects);
    setText('navAboutDesktop', dictionary.nav.about);
    setText('navContactDesktop', dictionary.nav.contact);
    setText('langToggleDesktop', dictionary.nav.switchLabel);
    setText('navHomeMobile', dictionary.nav.home);
    setText('navProjectsMobile', dictionary.nav.projects);
    setText('navAboutMobile', dictionary.nav.about);
    setText('navContactMobile', dictionary.nav.contact);
    setText('langToggleMobile', dictionary.nav.switchLabel);

    setHtml('heroTitle', dictionary.hero.title);
    setText('heroSubtitle', dictionary.hero.subtitle);
    setText('viewWorkCta', dictionary.hero.cta);

    setText('projectsHeading', dictionary.sections.projects);
    setText('p1Title', dictionary.projects.gw2.title);
    setText('p1Desc', dictionary.projects.gw2.desc);
    setText('p2Title', dictionary.projects.subnet.title);
    setText('p2Desc', dictionary.projects.subnet.desc);
    setText('p3Title', dictionary.projects.ipv6.title);
    setText('p3Desc', dictionary.projects.ipv6.desc);
    setText('p4Title', dictionary.projects.globalincom.title);
    setText('p4Desc', dictionary.projects.globalincom.desc);
    setText('p5Title', dictionary.projects.genetic.title);
    setText('p5Desc', dictionary.projects.genetic.desc);
    setText('p6Title', dictionary.projects.loan.title);
    setText('p6Desc', dictionary.projects.loan.desc);
    setText('p7Title', dictionary.projects.cdr.title);
    setText('p7Desc', dictionary.projects.cdr.desc);
    setText('p8Title', dictionary.projects.lastfm.title);
    setText('p8Desc', dictionary.projects.lastfm.desc);

    setText('p5Tag2', dictionary.projects.genetic.tag2);
    setText('p5Tag3', dictionary.projects.genetic.tag3);
    setText('p6Tag2', dictionary.projects.loan.tag2);
    setText('p7Tag3', dictionary.projects.cdr.tag3);

    ['p1', 'p2', 'p3', 'p4', 'p5', 'p6', 'p7', 'p8'].forEach(function(prefix) {
        setText(prefix + 'ViewProject', dictionary.labels.viewProject);
        setText(prefix + 'LiveDemo', dictionary.labels.liveDemo);
        setText(prefix + 'Preview', dictionary.labels.preview);
    });

    setText('aboutHeading', dictionary.sections.about);
    setHtml('aboutParagraph1', dictionary.about.p1);
    setHtml('aboutParagraph2', dictionary.about.p2);
    setText('skillsHeading', dictionary.sections.skills);
    setText('skill1', dictionary.skills.s1);
    setText('skill2', dictionary.skills.s2);
    setText('skill6', dictionary.skills.s6);

    setText('connectHeading', dictionary.sections.connect);
    setHtml('copyrightText', dictionary.footer.copyright);

    setText('modal-title', dictionary.labels.modalPreview);
    const externalLink = document.getElementById('modal-external-link');
    const previewFrame = document.getElementById('previewFrame');
    if (externalLink) {
        externalLink.title = dictionary.labels.openNewTab;
    }
    if (previewFrame) {
        previewFrame.title = dictionary.labels.modalPreview;
    }

    setStoredLanguage(dictionary.lang);
}

function toggleLanguage() {
    applyLanguage(currentLang === 'en' ? 'es' : 'en');
}

function toggleMobileMenu() {
    const mobileMenu = document.getElementById('mobileMenu');
    const menuButton = document.getElementById('mobileMenuButton');
    if (!mobileMenu || !menuButton) {
        return;
    }

    const isHidden = mobileMenu.classList.contains('hidden');
    mobileMenu.classList.toggle('hidden');
    menuButton.setAttribute('aria-expanded', String(isHidden));
}

function closeMobileMenu() {
    const mobileMenu = document.getElementById('mobileMenu');
    const menuButton = document.getElementById('mobileMenuButton');
    if (!mobileMenu || !menuButton) {
        return;
    }

    if (!mobileMenu.classList.contains('hidden')) {
        mobileMenu.classList.add('hidden');
        menuButton.setAttribute('aria-expanded', 'false');
    }
}

function openModal(url, projectKey) {
    const modal = document.getElementById('previewModal');
    const frame = document.getElementById('previewFrame');
    const modalTitle = document.getElementById('modal-title');
    const externalLink = document.getElementById('modal-external-link');
    if (!modal || !frame || !modalTitle || !externalLink) {
        return;
    }

    const dictionary = i18n[currentLang] || i18n.en;
    const project = dictionary.projects[projectKey];

    modalTitle.textContent = project ? project.title : dictionary.labels.modalPreview;
    externalLink.href = url;
    frame.src = url;
    modal.classList.remove('hidden');
    document.body.style.overflow = 'hidden';
}

function closeModal() {
    const modal = document.getElementById('previewModal');
    const frame = document.getElementById('previewFrame');
    if (!modal || !frame) {
        return;
    }

    modal.classList.add('hidden');
    frame.src = '';
    document.body.style.overflow = '';
}

window.openModal = openModal;
window.closeModal = closeModal;

document.addEventListener('keydown', function(event) {
    if (event.key === 'Escape') {
        closeModal();
    }
});

const mobileMenuButton = document.getElementById('mobileMenuButton');
const mobileNavLinks = document.querySelectorAll('.mobile-nav-link');
const langToggleDesktop = document.getElementById('langToggleDesktop');
const langToggleMobile = document.getElementById('langToggleMobile');

if (mobileMenuButton) {
    mobileMenuButton.addEventListener('click', toggleMobileMenu);
}

mobileNavLinks.forEach(function(link) {
    link.addEventListener('click', closeMobileMenu);
});

if (langToggleDesktop) {
    langToggleDesktop.addEventListener('click', toggleLanguage);
}

if (langToggleMobile) {
    langToggleMobile.addEventListener('click', function() {
        toggleLanguage();
        closeMobileMenu();
    });
}

window.addEventListener('resize', function() {
    if (window.innerWidth >= 768) {
        closeMobileMenu();
    }
});

const savedLanguage = getStoredLanguage();
applyLanguage(savedLanguage === 'es' ? 'es' : 'en');
